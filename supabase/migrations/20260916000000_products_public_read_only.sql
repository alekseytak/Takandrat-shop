-- Витрина: публично видны только видимые товары, и никто из публики их не меняет.
--
-- В живой базе стояло правило «Public products all»: роль public, команда ALL,
-- условие true. Это значило, что любой, кто открыл сайт, мог не только читать
-- скрытые товары, но и править каталог — цены, склад, видимость, — а также
-- удалять товары. Правило заменено на чтение только строк с is_visible = true;
-- права на запись публичному ключу не выдаются вовсе (служебная роль правила
-- RLS обходит, поэтому владелец и функции работают как раньше).
--
-- Проверка — `npm run check:rls`, проба «каталог нельзя править публичным
-- ключом»: она записывает в строку её же название и смотрит, пустили ли запись.
-- Применено к живой базе 15 сентября.

DROP POLICY IF EXISTS "Public products all" ON public.products;

CREATE POLICY products_visible_read ON public.products
  FOR SELECT TO anon, authenticated
  USING (is_visible = true);

-- Набор фотографий товара: витрина умеет показывать несколько снимков одного
-- изделия, а в базе лежала одна ссылка.
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS images jsonb;
